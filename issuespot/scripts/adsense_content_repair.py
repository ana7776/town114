def remove_corrupt_lines(text: str) -> str:
    lines = []
    for line in text.splitlines():
        if "??" in line:
            continue
        lines.append(line)
    return "\n".join(lines) + "\n"


def replace_trust(text: str) -> str:
    text = re.sub(r'\s*<aside class="article-trust"[\s\S]*?</aside>', "\n" + TRUST, text, count=1)
    if 'class="article-trust"' not in text:
        text = re.sub(r'(    <p class="page-meta">[\s\S]*?</p>)', r'\1\n' + TRUST, text, count=1)
    return text


def insert_snippet(text: str, snippet: str) -> str:
    if snippet.strip().splitlines()[0] in text:
        return text
    marker = '      <div class="source-box">'
    return text.replace(marker, snippet + marker, 1)


def main() -> None:
    for path in sorted((ROOT / "articles").glob("*.html")):
        if path.name == "index.html":
            continue
        text = path.read_text(encoding="utf-8")
        text = remove_corrupt_lines(text)
        text = replace_trust(text)
        rel = path.relative_to(ROOT).as_posix()
        if rel in SNIPPETS:
            text = insert_snippet(text, SNIPPETS[rel])
        path.write_text(text, encoding="utf-8", newline="")
        print("repaired", rel)

    deploy_articles = ROOT / "cloudflare-pages-site" / "articles"
    deploy_articles.mkdir(parents=True, exist_ok=True)
    for src in (ROOT / "articles").glob("*.html"):
        dst = deploy_articles / src.name
        dst.write_text(src.read_text(encoding="utf-8"), encoding="utf-8", newline="")
    print("synced deploy articles")


if __name__ == "__main__":
    main()
